const PDFDocument = require('pdfkit');
const prisma = require('../config/prisma');

const MONTHS = ['January','February','March','April','May','June','July','August','September','October','November','December'];

const formatINR = (val) => `Rs. ${parseFloat(val || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const mapExpenseType = (t) => ({ WASHING: 'Washing', FUEL: 'Fuel', VEHICLE_SERVICE: 'Vehicle Service', OFFICE: 'Office' }[t] || t);
const mapPaymentMethod = (m) => ({ SBI: 'SBI', CASH: 'Cash', UPI: 'UPI', NA: 'N/A' }[m] || m);

const BRAND_COLOR = '#1E40AF';
const LIGHT_BG = '#EFF6FF';
const TEXT_COLOR = '#1F2937';
const MUTED_COLOR = '#6B7280';

/**
 * Draw a professional PDF header
 */
const drawHeader = (doc, title, subtitle) => {
  doc.rect(0, 0, doc.page.width, 80).fill(BRAND_COLOR);
  doc.fillColor('#FFFFFF').fontSize(20).font('Helvetica-Bold').text('FleetCost', 40, 20);
  doc.fontSize(11).font('Helvetica').text('Vehicle Expense & Profitability Management', 40, 46);
  doc.fillColor('#FFFFFF').fontSize(16).font('Helvetica-Bold').text(title, 0, 25, { align: 'right', width: doc.page.width - 40 });
  doc.fontSize(10).font('Helvetica').text(subtitle, 0, 47, { align: 'right', width: doc.page.width - 40 });
  doc.fillColor(TEXT_COLOR);
  doc.moveDown(3);
};

const drawSummaryCard = (doc, x, y, label, value, color = BRAND_COLOR) => {
  doc.rect(x, y, 150, 55).lineWidth(1).strokeColor('#D1D5DB').stroke();
  doc.rect(x, y, 4, 55).fill(color);
  doc.fillColor(MUTED_COLOR).fontSize(8).font('Helvetica').text(label, x + 12, y + 10, { width: 130 });
  doc.fillColor(TEXT_COLOR).fontSize(12).font('Helvetica-Bold').text(value, x + 12, y + 28, { width: 130 });
  doc.fillColor(TEXT_COLOR);
};

const drawTableHeader = (doc, headers, colWidths, y) => {
  let x = 40;
  doc.rect(40, y - 4, headers.reduce((s, _, i) => s + colWidths[i], 0), 20).fill(BRAND_COLOR);
  headers.forEach((h, i) => {
    doc.fillColor('#FFFFFF').fontSize(8).font('Helvetica-Bold').text(h, x + 3, y, { width: colWidths[i] - 6 });
    x += colWidths[i];
  });
  doc.fillColor(TEXT_COLOR);
  return y + 20;
};

const drawTableRow = (doc, cells, colWidths, y, even = false) => {
  let x = 40;
  const rowWidth = colWidths.reduce((s, w) => s + w, 0);
  if (even) doc.rect(40, y - 2, rowWidth, 16).fill('#F8FAFF');
  cells.forEach((cell, i) => {
    doc.fillColor(TEXT_COLOR).fontSize(7.5).font('Helvetica').text(String(cell), x + 3, y, { width: colWidths[i] - 6 });
    x += colWidths[i];
  });
  doc.moveTo(40, y + 14).lineTo(40 + rowWidth, y + 14).strokeColor('#E5E7EB').lineWidth(0.5).stroke();
  doc.fillColor(TEXT_COLOR);
  return y + 16;
};

const drawFooter = (doc) => {
  const y = doc.page.height - 40;
  doc.moveTo(40, y).lineTo(doc.page.width - 40, y).strokeColor('#D1D5DB').lineWidth(0.5).stroke();
  doc.fillColor(MUTED_COLOR).fontSize(8).text(
    `Generated by FleetCost on ${new Date().toLocaleDateString('en-IN')}`,
    40, y + 8,
    { align: 'center', width: doc.page.width - 80 }
  );
};

/**
 * GET /api/export/pdf/monthly?month=8&year=2026
 */
const pdfMonthly = async (req, res, next) => {
  try {
    const { month, year } = req.query;
    if (!month || !year) return res.status(400).json({ success: false, message: 'Month and year required.' });

    const m = parseInt(month); const y = parseInt(year);
    const startDate = new Date(y, m - 1, 1);
    const endDate = new Date(y, m, 0, 23, 59, 59, 999);
    const where = { isDeleted: false, date: { gte: startDate, lte: endDate } };

    const [expenses, totals] = await Promise.all([
      prisma.expense.findMany({
        where, include: { vehicle: { select: { vehicleNumber: true } }, party: { select: { name: true } } },
        orderBy: { date: 'asc' },
      }),
      Promise.all(['WASHING','FUEL','VEHICLE_SERVICE','OFFICE'].map(t =>
        prisma.expense.aggregate({ where: { ...where, expenseType: t }, _sum: { amount: true } })
      )),
    ]);

    const [wash, fuel, serv, off] = totals.map(t => parseFloat(t._sum.amount || 0));
    const total = wash + fuel + serv + off;
    const paid = parseFloat((await prisma.expense.aggregate({ where: { ...where, paymentStatus: 'PAID' }, _sum: { amount: true } }))._sum.amount || 0);
    const unpaid = total - paid;

    const doc = new PDFDocument({ margin: 40, size: 'A4' });
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename=monthly_report_${y}_${m}.pdf`);
    doc.pipe(res);

    drawHeader(doc, 'Monthly Expense Report', `${MONTHS[m-1]} ${y}`);

    // Summary cards
    const cardY = 100;
    drawSummaryCard(doc, 40, cardY, 'Total Expense', formatINR(total), '#1E40AF');
    drawSummaryCard(doc, 200, cardY, 'Total Paid', formatINR(paid), '#16A34A');
    drawSummaryCard(doc, 360, cardY, 'Total Unpaid', formatINR(unpaid), '#DC2626');
    doc.moveDown(5);

    // Category breakdown
    let cy = cardY + 70;
    doc.fillColor(BRAND_COLOR).fontSize(11).font('Helvetica-Bold').text('Expense Breakdown', 40, cy);
    cy += 18;
    drawSummaryCard(doc, 40, cy, 'Washing', formatINR(wash), '#7C3AED');
    drawSummaryCard(doc, 200, cy, 'Fuel', formatINR(fuel), '#EA580C');
    drawSummaryCard(doc, 360, cy, 'Vehicle Service', formatINR(serv), '#0891B2');
    drawSummaryCard(doc, 40, cy + 65, 'Office', formatINR(off), '#65A30D');

    cy += 140;
    doc.fillColor(BRAND_COLOR).fontSize(11).font('Helvetica-Bold').text('Expense Details', 40, cy);
    cy += 18;

    const colWidths = [35, 70, 80, 80, 110, 70, 70];
    cy = drawTableHeader(doc, ['Date','Type','Vehicle','Party','Description/Service','Amount','Status'], colWidths, cy);

    expenses.forEach((e, idx) => {
      if (cy > doc.page.height - 80) { doc.addPage(); cy = 40; cy = drawTableHeader(doc, ['Date','Type','Vehicle','Party','Description/Service','Amount','Status'], colWidths, cy); }
      cy = drawTableRow(doc, [
        new Date(e.date).toLocaleDateString('en-IN'),
        mapExpenseType(e.expenseType),
        e.vehicle?.vehicleNumber || 'N/A',
        e.party?.name || '-',
        e.expenseDescription || e.serviceType || e.serviceExpenseType || '-',
        formatINR(e.amount),
        e.paymentStatus === 'PAID' ? 'Paid' : 'Unpaid',
      ], colWidths, cy, idx % 2 === 1);
    });

    if (cy > doc.page.height - 80) { doc.addPage(); cy = 40; }
    cy += 4;
    doc.rect(40, cy, colWidths.reduce((s,w)=>s+w,0), 18).fill('#EFF6FF');
    doc.fillColor(BRAND_COLOR).fontSize(9).font('Helvetica-Bold').text('TOTAL', 40+3, cy+4);
    doc.text(formatINR(total), 40 + colWidths.slice(0,5).reduce((s,w)=>s+w,0) + 3, cy+4);

    drawFooter(doc);
    doc.end();
  } catch (error) {
    next(error);
  }
};

/**
 * GET /api/export/pdf/yearly?year=2026
 */
const pdfYearly = async (req, res, next) => {
  try {
    const { year } = req.query;
    if (!year) return res.status(400).json({ success: false, message: 'Year required.' });

    const y = parseInt(year);
    const startDate = new Date(y, 0, 1);
    const endDate = new Date(y, 11, 31, 23, 59, 59, 999);
    const where = { isDeleted: false, date: { gte: startDate, lte: endDate } };

    const [total, paid, unpaid, wash, fuel, serv, off] = await Promise.all([
      prisma.expense.aggregate({ where, _sum: { amount: true } }),
      prisma.expense.aggregate({ where: { ...where, paymentStatus: 'PAID' }, _sum: { amount: true } }),
      prisma.expense.aggregate({ where: { ...where, paymentStatus: 'UNPAID' }, _sum: { amount: true } }),
      prisma.expense.aggregate({ where: { ...where, expenseType: 'WASHING' }, _sum: { amount: true } }),
      prisma.expense.aggregate({ where: { ...where, expenseType: 'FUEL' }, _sum: { amount: true } }),
      prisma.expense.aggregate({ where: { ...where, expenseType: 'VEHICLE_SERVICE' }, _sum: { amount: true } }),
      prisma.expense.aggregate({ where: { ...where, expenseType: 'OFFICE' }, _sum: { amount: true } }),
    ]);

    const monthlyData = await prisma.$queryRaw`
      SELECT EXTRACT(MONTH FROM date)::int AS month, SUM(amount)::float AS total
      FROM expenses WHERE "isDeleted" = false AND EXTRACT(YEAR FROM date) = ${y}
      GROUP BY month ORDER BY month
    `;

    const doc = new PDFDocument({ margin: 40, size: 'A4' });
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename=yearly_report_${y}.pdf`);
    doc.pipe(res);

    drawHeader(doc, 'Yearly Expense Report', `Year ${y}`);

    const cardY = 100;
    drawSummaryCard(doc, 40, cardY, 'Total Expense', formatINR(total._sum.amount), '#1E40AF');
    drawSummaryCard(doc, 200, cardY, 'Total Paid', formatINR(paid._sum.amount), '#16A34A');
    drawSummaryCard(doc, 360, cardY, 'Total Unpaid', formatINR(unpaid._sum.amount), '#DC2626');

    let cy = cardY + 70;
    drawSummaryCard(doc, 40, cy, 'Washing', formatINR(wash._sum.amount), '#7C3AED');
    drawSummaryCard(doc, 200, cy, 'Fuel', formatINR(fuel._sum.amount), '#EA580C');
    drawSummaryCard(doc, 360, cy, 'Service', formatINR(serv._sum.amount), '#0891B2');
    drawSummaryCard(doc, 40, cy + 65, 'Office', formatINR(off._sum.amount), '#65A30D');

    cy += 140;
    doc.fillColor(BRAND_COLOR).fontSize(11).font('Helvetica-Bold').text('Monthly Breakdown', 40, cy);
    cy += 18;

    const colWidths = [120, 120, 120, 115, 40];
    cy = drawTableHeader(doc, ['Month', 'Total Expense', 'Paid', 'Unpaid', ''], colWidths, cy);

    for (let i = 0; i < 12; i++) {
      const found = monthlyData.find(r => r.month === i + 1);
      const monthTotal = found ? parseFloat(found.total) : 0;
      cy = drawTableRow(doc, [MONTHS[i], formatINR(monthTotal), '-', '-', ''], colWidths, cy, i % 2 === 1);
    }

    drawFooter(doc);
    doc.end();
  } catch (error) {
    next(error);
  }
};

/**
 * GET /api/export/pdf/profitability?year=2026
 */
const pdfProfitability = async (req, res, next) => {
  try {
    const { year } = req.query;
    if (!year) return res.status(400).json({ success: false, message: 'Year required.' });

    const y = parseInt(year);
    const dateFilter = { gte: new Date(y, 0, 1), lte: new Date(y, 11, 31, 23, 59, 59, 999) };
    const vehicles = await prisma.vehicle.findMany({ orderBy: { vehicleNumber: 'asc' } });

    const rows = await Promise.all(vehicles.map(async (v) => {
      const expWhere = { isDeleted: false, vehicleId: v.id, date: dateFilter };
      const [costRes, revRecord] = await Promise.all([
        prisma.expense.aggregate({ where: expWhere, _sum: { amount: true } }),
        prisma.vehicleRevenue.findUnique({ where: { vehicleId_year: { vehicleId: v.id, year: y } } }),
      ]);
      const cost = parseFloat(costRes._sum.amount || 0);
      const revenue = revRecord ? parseFloat(revRecord.revenueAmount) : 0;
      const profit = revenue - cost;
      const margin = revenue > 0 ? (profit / revenue) * 100 : null;
      return { vehicle: v.vehicleNumber, model: v.modelName, revenue, cost, profit, margin };
    }));

    const doc = new PDFDocument({ margin: 40, size: 'A4', layout: 'landscape' });
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename=profitability_${y}.pdf`);
    doc.pipe(res);

    drawHeader(doc, 'Vehicle Profitability Report', `Year ${y}`);

    let cy = 110;
    const colWidths = [100, 120, 110, 110, 110, 90, 110];
    cy = drawTableHeader(doc, ['Vehicle', 'Model', 'Revenue', 'Total Cost', 'Profit/Loss', 'Margin %', 'Status'], colWidths, cy);

    rows.forEach((r, idx) => {
      const status = r.profit > 0 ? 'Profitable' : r.profit < 0 ? 'Loss' : 'Break Even';
      cy = drawTableRow(doc, [
        r.vehicle, r.model,
        formatINR(r.revenue), formatINR(r.cost),
        formatINR(r.profit),
        r.margin !== null ? r.margin.toFixed(2) + '%' : 'N/A',
        status,
      ], colWidths, cy, idx % 2 === 1);
    });

    drawFooter(doc);
    doc.end();
  } catch (error) {
    next(error);
  }
};

module.exports = { pdfMonthly, pdfYearly, pdfProfitability };
